import React, { useState } from 'react';
import { FarmSettings, PLSummary, LandPlot, PartnerDistribution, FinancialItem } from '../types';
import { formatCurrency } from '../utils/calculations';
import { ArrowRight, ArrowDown, Info, ShieldCheck, Users, DollarSign, Wallet, Sprout, CheckCircle2 } from 'lucide-react';

interface MoneyFlowTabProps {
  settings: FarmSettings;
  pl: PLSummary;
  lands: LandPlot[];
  distributions: PartnerDistribution[];
  items: FinancialItem[];
  activeYear: number;
}

export const MoneyFlowTab: React.FC<MoneyFlowTabProps> = ({
  settings,
  pl,
  lands,
  distributions,
  items,
  activeYear,
}) => {
  const [selectedNode, setSelectedNode] = useState<{
    title: string;
    amount: number;
    description: string;
    percentage: string;
    details?: string[];
  }>({
    title: 'Gross Agricultural Revenue',
    amount: pl.grossRevenue,
    description: 'Total farm sales realized across all parcels including grain cash contracts, forward hedges, and USDA incentives.',
    percentage: '100% of top-line inflow',
    details: Object.entries(pl.revenueByCategory).map(([cat, amt]) => `${cat}: ${formatCurrency(amt, settings.currency)}`),
  });

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-2 border-b border-slate-200 dark:border-slate-800">
        <div>
          <h2 className="text-xl font-bold tracking-tight text-slate-900 dark:text-white">
            Visual Money Flow &amp; Process Diagram
          </h2>
          <p className="text-xs text-slate-500">
            Interactive capital flow from Gross Revenue &rarr; Production Costs &rarr; Operating Reserve &rarr; Partner Distributions ({activeYear})
          </p>
        </div>
      </div>

      {/* Main Flow Canvas with responsive cards and SVG connectors */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Left Column: Visual Process Flow (8 cols) */}
        <div className="lg:col-span-8 space-y-6 p-6 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
          {/* STEP 1: Gross Revenue */}
          <div className="space-y-2">
            <span className="text-[11px] font-bold text-slate-400 uppercase tracking-wider block">
              Phase 1: Inflow Origin
            </span>
            <div
              onClick={() =>
                setSelectedNode({
                  title: 'Total Gross Agricultural Revenue',
                  amount: pl.grossRevenue,
                  description: 'All top-line cash and deferred contract proceeds generated by managed land units.',
                  percentage: '100%',
                  details: Object.entries(pl.revenueByCategory).map(([c, a]) => `${c}: ${formatCurrency(a, settings.currency)}`),
                })
              }
              className="p-4 rounded-xl border-2 border-emerald-500 bg-emerald-50/20 dark:bg-emerald-950/20 hover:shadow-md transition-all cursor-pointer flex items-center justify-between"
            >
              <div className="flex items-center gap-3">
                <div className="w-10 h-10 rounded-lg bg-emerald-600 text-white flex items-center justify-center font-bold">
                  <DollarSign className="w-6 h-6" />
                </div>
                <div>
                  <h4 className="text-sm font-bold text-slate-900 dark:text-white">Total Gross Farm Revenue</h4>
                  <p className="text-xs text-slate-500">{lands.length} Managed Land Parcels</p>
                </div>
              </div>
              <div className="text-right">
                <p className="text-lg font-mono font-bold text-emerald-700 dark:text-emerald-400">
                  {formatCurrency(pl.grossRevenue, settings.currency)}
                </p>
                <span className="text-[11px] text-slate-400 font-medium">100% of Operating Inflow</span>
              </div>
            </div>
          </div>

          {/* Flow Connector Arrow */}
          <div className="flex justify-center text-slate-400">
            <div className="flex flex-col items-center">
              <span className="text-[10px] uppercase font-bold text-slate-400 mb-0.5">Deduct Direct Input Costs</span>
              <ArrowDown className="w-5 h-5 text-slate-400" />
            </div>
          </div>

          {/* STEP 2: Production Costs Split */}
          <div className="space-y-2">
            <span className="text-[11px] font-bold text-slate-400 uppercase tracking-wider block">
              Phase 2: Direct Production &amp; Operational Costs
            </span>
            <div
              onClick={() =>
                setSelectedNode({
                  title: 'Direct Production Expenditures',
                  amount: pl.totalExpenses,
                  description: 'Direct cash expenditures absorbed during pre-plant, application, irrigation, and harvest operations.',
                  percentage: `${pl.grossRevenue > 0 ? ((pl.totalExpenses / pl.grossRevenue) * 100).toFixed(1) : 0}% of revenue`,
                  details: Object.entries(pl.expenseByCategory).map(([c, a]) => `${c}: ${formatCurrency(a, settings.currency)}`),
                })
              }
              className="p-4 rounded-xl border border-rose-200 dark:border-rose-900/60 bg-rose-50/30 dark:bg-rose-950/20 hover:shadow-md transition-all cursor-pointer flex items-center justify-between"
            >
              <div className="flex items-center gap-3">
                <div className="w-10 h-10 rounded-lg bg-rose-600 text-white flex items-center justify-center font-bold">
                  <Sprout className="w-6 h-6" />
                </div>
                <div>
                  <h4 className="text-sm font-bold text-slate-900 dark:text-white">Total Direct Farm Expenses</h4>
                  <p className="text-xs text-slate-500">Seeds, Fertilizer, Fuel, Irrigation, Labor &amp; Storage</p>
                </div>
              </div>
              <div className="text-right">
                <p className="text-lg font-mono font-bold text-rose-600 dark:text-rose-400">
                  -{formatCurrency(pl.totalExpenses, settings.currency)}
                </p>
                <span className="text-[11px] text-slate-400 font-medium">
                  {pl.grossRevenue > 0 ? ((pl.totalExpenses / pl.grossRevenue) * 100).toFixed(1) : 0}% of gross
                </span>
              </div>
            </div>
          </div>

          {/* Flow Connector Arrow */}
          <div className="flex justify-center text-slate-400">
            <div className="flex flex-col items-center">
              <span className="text-[10px] uppercase font-bold text-slate-400 mb-0.5">Calculates Net Operating Income</span>
              <ArrowDown className="w-5 h-5 text-slate-400" />
            </div>
          </div>

          {/* STEP 3 & 4: Net Operating Profit & Farm Reserve Split */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            {/* Net Operating Profit */}
            <div
              onClick={() =>
                setSelectedNode({
                  title: 'Net Operating Income (EBIT)',
                  amount: pl.netProfit,
                  description: 'Total operational surplus before statutory partner distributions or contingency withholdings.',
                  percentage: `${pl.profitMarginPercent}% Operating Margin`,
                  details: [
                    `Gross Revenue: ${formatCurrency(pl.grossRevenue, settings.currency)}`,
                    `Total Production Expenses: -${formatCurrency(pl.totalExpenses, settings.currency)}`,
                    `Net Profit Margin: ${pl.profitMarginPercent}%`,
                    `Per Acre Net: ${formatCurrency(pl.netProfitPerAcre, settings.currency)}/ac`,
                  ],
                })
              }
              className="p-4 rounded-xl border border-slate-200 dark:border-slate-700 bg-slate-50 dark:bg-slate-800/40 hover:shadow-md transition-all cursor-pointer"
            >
              <div className="flex items-center gap-2 mb-2">
                <Wallet className="w-5 h-5 text-slate-700 dark:text-slate-300" />
                <h4 className="text-xs font-bold text-slate-900 dark:text-white">Net Operating Profit</h4>
              </div>
              <p className="text-xl font-mono font-bold text-slate-900 dark:text-white">
                {formatCurrency(pl.netProfit, settings.currency)}
              </p>
              <span className="text-[11px] text-slate-500 font-medium block mt-1">
                {pl.profitMarginPercent}% Operating Profit Margin
              </span>
            </div>

            {/* Farm Reserve Retained */}
            <div
              onClick={() =>
                setSelectedNode({
                  title: 'Farm Retained Operating Reserve',
                  amount: pl.retainedReserve,
                  description: 'Contingency reserve withheld inside farm partnership operating treasury for winter equipment service and input hedging.',
                  percentage: `${settings.reserveFundPercent}% of positive net profit`,
                  details: [
                    `Policy Reserve Target: ${settings.reserveFundPercent}%`,
                    `Retained Capital: ${formatCurrency(pl.retainedReserve, settings.currency)}`,
                    `Primary Purpose: Off-season cash flow buffer and seed pre-orders`,
                  ],
                })
              }
              className="p-4 rounded-xl border border-amber-200 dark:border-amber-900/60 bg-amber-50/30 dark:bg-amber-950/20 hover:shadow-md transition-all cursor-pointer"
            >
              <div className="flex items-center gap-2 mb-2">
                <ShieldCheck className="w-5 h-5 text-amber-600" />
                <h4 className="text-xs font-bold text-amber-900 dark:text-amber-200">
                  Retained Farm Reserve ({settings.reserveFundPercent}%)
                </h4>
              </div>
              <p className="text-xl font-mono font-bold text-amber-700 dark:text-amber-400">
                {formatCurrency(pl.retainedReserve, settings.currency)}
              </p>
              <span className="text-[11px] text-slate-500 font-medium block mt-1">
                Preserves Farm Liquidity Escrow
              </span>
            </div>
          </div>

          {/* Flow Connector Arrow */}
          <div className="flex justify-center text-slate-400">
            <div className="flex flex-col items-center">
              <span className="text-[10px] uppercase font-bold text-slate-400 mb-0.5">Disburses to Equity Partners</span>
              <ArrowDown className="w-5 h-5 text-slate-400" />
            </div>
          </div>

          {/* STEP 5: Partner Equity Splits */}
          <div className="space-y-2">
            <div className="flex items-center justify-between">
              <span className="text-[11px] font-bold text-slate-400 uppercase tracking-wider block">
                Phase 3: Multi-Partner Equity Disbursements
              </span>
              <span className="text-xs font-mono font-bold text-emerald-600">
                Total Pool: {formatCurrency(pl.distributableProfit, settings.currency)}
              </span>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
              {distributions.map((dist) => (
                <div
                  key={dist.partner.id}
                  onClick={() =>
                    setSelectedNode({
                      title: `${dist.partner.name} Equity Payout`,
                      amount: dist.netPayout,
                      description: `Net capital distribution disbursed according to ${dist.partner.sharePercent}% equity ownership share.`,
                      percentage: `${dist.partner.sharePercent}% Partner Equity Share`,
                      details: [
                        `Gross Allocated: ${formatCurrency(dist.allocatedGrossProfit, settings.currency)}`,
                        `Reserve Share: -${formatCurrency(dist.retainedReserveContribution, settings.currency)}`,
                        `Net Payout: ${formatCurrency(dist.netPayout, settings.currency)}`,
                        `Method: ${dist.partner.payoutPreference}`,
                        `Role: ${dist.partner.role}`,
                      ],
                    })
                  }
                  className="p-3.5 rounded-xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-800/80 hover:border-emerald-500/60 transition-all cursor-pointer"
                >
                  <div className="flex items-center justify-between text-xs mb-1">
                    <span className="font-bold text-slate-900 dark:text-white truncate">
                      {dist.partner.name}
                    </span>
                    <span className="font-mono font-bold text-emerald-600">{dist.partner.sharePercent}%</span>
                  </div>
                  <p className="text-base font-mono font-bold text-emerald-700 dark:text-emerald-300">
                    {formatCurrency(dist.netPayout, settings.currency)}
                  </p>
                  <span className="text-[10px] text-slate-400 block mt-1 truncate">
                    {dist.partner.role}
                  </span>
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Right Column: Node Inspector & Educational Explainer (4 cols) */}
        <div className="lg:col-span-4 space-y-4">
          <div className="p-5 rounded-xl bg-slate-50 dark:bg-slate-900/60 border border-slate-200 dark:border-slate-800 sticky top-20 space-y-4">
            <div className="flex items-center gap-2 text-xs font-bold text-slate-700 dark:text-slate-300">
              <Info className="w-4 h-4 text-emerald-600" />
              <span>Flow Inspector</span>
            </div>

            <div>
              <span className="text-[10px] text-slate-400 uppercase font-semibold block">Inspected Node</span>
              <h3 className="text-base font-bold text-slate-900 dark:text-white mt-0.5">
                {selectedNode.title}
              </h3>
              <p className="text-2xl font-mono font-bold text-emerald-600 dark:text-emerald-400 mt-1">
                {formatCurrency(selectedNode.amount, settings.currency)}
              </p>
              <span className="text-xs font-mono font-medium text-slate-500 block mt-0.5">
                {selectedNode.percentage}
              </span>
            </div>

            <p className="text-xs text-slate-600 dark:text-slate-400 leading-relaxed border-t border-slate-200 dark:border-slate-800 pt-3">
              {selectedNode.description}
            </p>

            {selectedNode.details && selectedNode.details.length > 0 && (
              <div className="space-y-1.5 border-t border-slate-200 dark:border-slate-800 pt-3">
                <span className="text-[10px] text-slate-400 font-semibold uppercase block">Sub-Item Allocations</span>
                <div className="space-y-1 max-h-[220px] overflow-y-auto pr-1">
                  {selectedNode.details.map((item, idx) => (
                    <div
                      key={idx}
                      className="p-1.5 rounded bg-white dark:bg-slate-800 text-xs text-slate-700 dark:text-slate-300 border border-slate-200 dark:border-slate-700 flex items-center justify-between font-mono"
                    >
                      <span className="truncate pr-2 font-sans">{item.split(':')[0]}</span>
                      <span className="font-bold shrink-0">{item.split(':')[1]}</span>
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};
